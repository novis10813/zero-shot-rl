"""Aggregate T6.4 additive-rule ANFIS 10-seed results with T6.2 baselines.

Computes per-environment and 4-env mean Table 6 metrics (`select_iqm`, `final_iqm`, and
final-step per-task scores) across all 10 finetune seeds (`ft1000..ft1090`) using
`analysis.table6_aggregate`. Writes `data/summary.csv` and `data/summary.md`.

Usage (repo root):
    PYTHONPATH=.:tasks/T6.4-fuzzy-add-rule uv run python -m analyze.summarize
    PYTHONPATH=.:tasks/T6.4-fuzzy-add-rule uv run python -m analyze.summarize --check
"""

from argparse import ArgumentParser
from pathlib import Path
from typing import Dict, List, Sequence

import numpy as np
import pandas as pd

from analysis.table6_aggregate import TASKS
from analysis.table6_aggregate import aggregate as table6_aggregate
from zero_shot_rl.provenance import no_clobber

ENVS = ("friction_mild", "friction_high_mild", "actuator_mild", "actuator_high_mild")
SEEDS = tuple(f"ft{s}" for s in range(1000, 1100, 10))

T64_INPUTS = Path("tasks/T6.4-fuzzy-add-rule/data/inputs")
T62_INPUTS = Path("tasks/T6.2-faster-update-algo/data/inputs")

CONDITIONS = (
    ("all37_first (T6.4)", T64_INPUTS, "all37_first"),
    ("8_first (T6.4)", T64_INPUTS, "8_first"),
    ("all37_zero (T6.4)", T64_INPUTS, "all37_zero"),
    ("Cartesian 4 sensors (T6.2)", T62_INPUTS, "cmaes_anfis"),
    ("Cartesian custom (T6.2)", T62_INPUTS, "cmaes_anfis_custom"),
    ("Direct z full-cov (T6.2)", T62_INPUTS, "cmaes_z"),
)


def condition_rows(label: str, root: Path, cond: str, seeds: Sequence[str] = SEEDS) -> List[Dict[str, object]]:
    rows: List[Dict[str, object]] = []
    for env in ENVS:
        runs = [pd.read_csv(root / cond / env / s / "table6.csv").set_index("step")[TASKS] for s in seeds]
        steps = runs[0].index
        if not all(r.index.equals(steps) for r in runs):
            raise ValueError(f"{cond}/{env}: runs must share eval steps")
        arr = np.stack([r.to_numpy(dtype=np.float64) for r in runs])  # [seeds, steps, tasks]
        per_step = table6_aggregate(arr)
        best = int(np.argmax(per_step))
        row: Dict[str, object] = {
            "env": env,
            "condition": label,
            "selected_step": int(steps[best]),
            "select_iqm": float(per_step[best]),
            "final_iqm": float(per_step[-1]),
        }
        row.update({t: float(arr[:, -1, i].mean()) for i, t in enumerate(TASKS)})
        rows.append(row)
    return rows


def build_summary_df() -> pd.DataFrame:
    rows: List[Dict[str, object]] = []
    for label, root, cond in CONDITIONS:
        c_rows = condition_rows(label, root, cond)
        rows.extend(c_rows)
        mean_row: Dict[str, object] = {
            "env": "4-env mean",
            "condition": label,
            "selected_step": -1,
            "select_iqm": float(np.mean([r["select_iqm"] for r in c_rows])),
            "final_iqm": float(np.mean([r["final_iqm"] for r in c_rows])),
        }
        mean_row.update({t: float(np.mean([r[t] for r in c_rows])) for t in TASKS})
        rows.append(mean_row)
    return pd.DataFrame(rows)


def render_markdown(df: pd.DataFrame) -> str:
    lines = [
        "| env | condition | selected_step | select_iqm | final_iqm | stand | walk | run | flip |",
        "|---|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for _, r in df.iterrows():
        step_str = "-" if int(r["selected_step"]) < 0 else str(int(r["selected_step"]))
        lines.append(
            f"| {r['env']} | {r['condition']} | {step_str} | "
            f"{r['select_iqm']:.1f} | {r['final_iqm']:.1f} | "
            f"{r['stand']:.1f} | {r['walk']:.1f} | {r['run']:.1f} | {r['flip']:.1f} |"
        )
    return "\n".join(lines) + "\n"


def main(argv: Sequence[str] = None) -> None:
    parser = ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out_dir", default="tasks/T6.4-fuzzy-add-rule/data")
    parser.add_argument("--check", action="store_true", help="Verify stored summary files match regenerated bytes.")
    args = parser.parse_args(argv)

    out_dir = Path(args.out_dir)
    df = build_summary_df()
    csv_bytes = df.to_csv(index=False).encode("utf-8")
    md_bytes = render_markdown(df).encode("utf-8")

    if args.check:
        for name, expected in (("summary.csv", csv_bytes), ("summary.md", md_bytes)):
            actual = (out_dir / name).read_bytes()
            if actual != expected:
                raise SystemExit(f"{out_dir / name} differs from regenerated output")
        print("summary.csv and summary.md match byte for byte.")
        return

    out_dir.mkdir(parents=True, exist_ok=True)
    with no_clobber(out_dir / "summary.csv") as tmp:
        Path(tmp).write_bytes(csv_bytes)
    with no_clobber(out_dir / "summary.md") as tmp:
        Path(tmp).write_bytes(md_bytes)
    print(render_markdown(df))


if __name__ == "__main__":
    main()
